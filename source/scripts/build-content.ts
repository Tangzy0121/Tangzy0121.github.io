// Content compiler: content/ (markdown + profile.json) -> src/generated/content.ts
// Runnable standalone. Fails the build on dead links so the site never ships them.
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

// Last update = date of the latest git commit (like a static site rebuilt from its repo); today if git is unavailable.
export function lastUpdate(cwd: string): string {
  try {
    return execSync('git log -1 --format=%cs', { cwd, encoding: 'utf8' }).trim() || new Date().toISOString().slice(0, 10);
  } catch {
    return new Date().toISOString().slice(0, 10);
  }
}

type Tree = { [name: string]: Tree | string };

export function walk(dir: string): Tree {
  const out: Tree = {};
  for (const name of readdirSync(dir).sort()) {
    if (name === 'profile.json' || name.startsWith('.')) continue;
    const p = join(dir, name);
    out[name] = statSync(p).isDirectory() ? walk(p) : readFileSync(p, 'utf8').replace(/\s+$/, '');
  }
  return out;
}

function get(tree: Tree, path: string): Tree | string | undefined {
  let cur: Tree | string | undefined = tree;
  for (const s of path.replace(/^~\//, '').split('/').filter(Boolean)) {
    if (typeof cur !== 'object') return undefined;
    cur = cur[s];
  }
  return cur;
}

/** Returns a list of problems: links to "#", cmd: links to missing files, missing pages. */
export function validate(tree: Tree, profile: { pages: Record<string, string> }): string[] {
  const errs: string[] = [];
  for (const [cmd, file] of Object.entries(profile.pages))
    if (typeof get(tree, file) !== 'string') errs.push(`page '${cmd}' -> missing ${file}`);
  const visit = (t: Tree, base: string) => {
    for (const [name, v] of Object.entries(t)) {
      if (typeof v === 'object') { visit(v, `${base}${name}/`); continue; }
      for (const m of v.matchAll(/\[([^\]]+)\]\(([^)]*)\)/g)) {
        const url = m[2];
        if (url === '' || url === '#') errs.push(`${base}${name}: dead link "${m[1]}"`);
        const c = url.match(/^cmd:cat (\S+)$/);
        if (c && typeof get(tree, c[1]) !== 'string') errs.push(`${base}${name}: cmd link to missing ${c[1]}`);
      }
    }
  };
  visit(tree, '');
  return errs;
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const contentDir = join(root, 'content');
  const profile = JSON.parse(readFileSync(join(contentDir, 'profile.json'), 'utf8'));
  profile.lastUpdate = lastUpdate(root);
  const tree = walk(contentDir);
  const errs = validate(tree, profile);
  if (errs.length) {
    console.error('content errors:\n  ' + errs.join('\n  '));
    process.exit(1);
  }
  mkdirSync(join(root, 'src/generated'), { recursive: true });
  writeFileSync(
    join(root, 'src/generated/content.ts'),
    '// GENERATED by scripts/build-content.ts from content/. Do not edit.\n' +
      `export const profile = ${JSON.stringify(profile, null, 2)} as const;\n` +
      `export const tree: Record<string, unknown> = ${JSON.stringify(tree, null, 2)};\n`,
  );
  console.log(`content: ${Object.keys(tree).length} top-level entries, ${Object.keys(profile.pages).length} pages`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
